/**
 * SIMULATION RUNNER
 *
 * Runs weekly-finalize and daily-update scripts for each historical week
 * to generate realistic historical score and portfolio data.
 *
 * HOW TO RUN:
 *   1. Run clear-test-data.sql in Supabase SQL Editor
 *   2. Run seed-test-data.sql in Supabase SQL Editor
 *   3. Run: npx ts-node --skip-project src/scripts/run-simulation.ts
 */

import { execSync } from "child_process";
import * as fs from "fs";
import * as path from "path";

// ─── CONFIG ──────────────────────────────────────────────────────────────────

const SIMULATION_WEEKS = [
  {
    monday: "2026-09-07",
    through: "2026-09-11",
    // September 7 is Labor Day; the market is closed.
    trading: ["2026-09-08", "2026-09-09", "2026-09-10", "2026-09-11"],
  },
  {
    monday: "2026-09-14",
    through: "2026-09-18",
    trading: ["2026-09-14", "2026-09-15", "2026-09-16", "2026-09-17", "2026-09-18"],
  },
  {
    monday: "2026-09-21",
    through: "2026-09-25",
    trading: ["2026-09-21", "2026-09-22", "2026-09-23", "2026-09-24", "2026-09-25"],
  },
  {
    monday: "2026-09-28",
    through: "2026-10-01",
    trading: ["2026-09-28", "2026-09-29", "2026-09-30", "2026-10-01"],
  },
];

const SIMULATION_CONFIG_PATH = path.join(
  process.cwd(),
  "src/config/simulation.ts"
);
const SIMULATION_TIME_ZONE = "America/New_York";

// ─── HELPERS ─────────────────────────────────────────────────────────────────

function getUtcIsoForNewYorkTime(date: string, time: string): string {
  const [year, month, day] = date.split("-").map(Number);
  const [hour, minute] = time.split(":").map(Number);
  const utcGuess = Date.UTC(year, month - 1, day, hour, minute);
  const localParts = new Intl.DateTimeFormat("en-US", {
    timeZone: SIMULATION_TIME_ZONE,
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
    hourCycle: "h23",
  }).formatToParts(new Date(utcGuess));
  const part = (type: string) => Number(localParts.find((item) => item.type === type)?.value);
  const representedUtc = Date.UTC(
    part("year"),
    part("month") - 1,
    part("day"),
    part("hour"),
    part("minute"),
    part("second")
  );
  const offset = representedUtc - utcGuess;

  return new Date(utcGuess - offset).toISOString();
}

function setSimulationDate(date: string, time: string) {
  const simulationInstant = getUtcIsoForNewYorkTime(date, time);
  const content = `
// AUTO-GENERATED by run-simulation.ts — do not edit manually
export const SIMULATION_DATE: string | null = "${simulationInstant}";

export function getSimulationDate(): Date {
  return SIMULATION_DATE ? new Date(SIMULATION_DATE) : new Date();
}

export function isSimulationMode(): boolean {
  return SIMULATION_DATE !== null;
}
`.trimStart();

  fs.writeFileSync(SIMULATION_CONFIG_PATH, content);
  console.log(`   ⏱  Simulation time set to ${date} ${time} ${SIMULATION_TIME_ZONE}`);
}

function clearSimulationDate() {
  const content = `
// AUTO-GENERATED by run-simulation.ts — do not edit manually
export const SIMULATION_DATE: string | null = null;

export function getSimulationDate(): Date {
  return new Date();
}

export function isSimulationMode(): boolean {
  return false;
}
`.trimStart();

  fs.writeFileSync(SIMULATION_CONFIG_PATH, content);
  console.log(`   ⏱  Simulation date cleared — back to live mode`);
}

function runScript(scriptPath: string) {
  console.log(`   ▶  Running ${path.basename(scriptPath)}...`);
  try {
    execSync(
      `npx tsx ${scriptPath}`, // <--- Change "ts-node --skip-project" to "tsx"
      { stdio: "inherit" }
    );
  } catch (err) {
    console.error(`   ❌ Script failed: ${scriptPath}`);
    throw err;
  }
}

function sleep(ms: number) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

// ─── MAIN ────────────────────────────────────────────────────────────────────

async function main() {
  const weeklyScript = path.join(process.cwd(), "src/scripts/weekly-finalize.ts");
  const dailyScript  = path.join(process.cwd(), "src/scripts/daily-update.ts");

  console.log("\n🚀 Starting simulation run");
  console.log(`   Weeks to simulate: ${SIMULATION_WEEKS.length}`);
  const totalRuns = SIMULATION_WEEKS.reduce((sum, week) => sum + 1 + week.trading.length, 0);
  console.log(`   Total script runs: ${totalRuns} (weekly finalize plus each trading day)\n`);

  for (const week of SIMULATION_WEEKS) {
    console.log(`\n${"─".repeat(60)}`);
    console.log(`📅 Week of ${week.monday} → ${week.through}`);
    console.log(`${"─".repeat(60)}`);

    // ── Monday 4am ET: weekly finalize (builds group portfolio, opening prices) ──
    console.log(`\n[Monday 4am ET] Weekly finalize — ${week.monday}`);
    setSimulationDate(week.monday, "04:00");
    runScript(weeklyScript);
    await sleep(1000);

    // ── Trading days 5pm ET: daily update (scores + daily snapshots) ──
    for (const tradingDay of week.trading) {
      console.log(`\n[5pm ET] Daily update — ${tradingDay}`);
      setSimulationDate(tradingDay, "17:00");
      runScript(dailyScript);
      await sleep(1000);
    }
  }

  // ── Reset simulation config when done ──
  console.log(`\n${"─".repeat(60)}`);
  clearSimulationDate();
  console.log("\n✅ Simulation complete.");
  console.log("   Check Supabase: scores, group_portfolio_daily, stock_prices");
}

main().catch((err) => {
  console.error("\n💥 Simulation failed:", err);
  clearSimulationDate(); // always reset even on failure
  process.exit(1);
});